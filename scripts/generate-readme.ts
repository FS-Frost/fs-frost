// Regenerates the project tables in README.md (English) and README.es.md (Spanish)
// from mai-tools' tools.json, the single source of truth for every listed project.
//
// Usage:
//   bun scripts/generate-readme.ts                                  # published JSON
//   bun scripts/generate-readme.ts ../mai-tools/static/tools.json   # local checkout

import { defaultSource, loadTools, localize, maiToolsUrl, type Locale, type Tool } from "./tools.ts";

const startMarker = "<!-- tools:start -->";
const endMarker = "<!-- tools:end -->";

type Readme = {
    path: URL;
    locale: Locale;
    headers: [string, string, string, string];
    /** Display name per category; categories missing here keep their tools.json name. */
    categories: Record<string, string>;
};

const readmes: Readme[] = [
    {
        path: new URL("../README.md", import.meta.url),
        locale: "en",
        headers: ["Category", "Project", "Description", "Stack"],
        categories: {},
    },
    {
        path: new URL("../README.es.md", import.meta.url),
        locale: "es",
        headers: ["Categoría", "Proyecto", "Descripción", "Stack"],
        // Same labels as the "es" dictionary in mai-tools' src/lib/text.ts.
        categories: {
            AI: "IA",
            Coding: "Programación",
            Converters: "Conversores",
            Images: "Imágenes",
            Learning: "Aprendizaje",
            "Plain text": "Texto plano",
            SQL: "SQL",
            Translation: "Traducción",
            Fun: "Diversión",
        },
    },
];

/** shields.io badge path per stack, matching the colors used by mai-tools. */
const badges: Record<string, string> = {
    Svelte: "Svelte-FF3E00?style=flat&logo=svelte&logoColor=white",
    React: "React-20232A?style=flat&logo=react&logoColor=61DAFB",
    TypeScript: "TypeScript-3178C6?style=flat&logo=typescript&logoColor=white",
    JavaScript: "JavaScript-F7DF1E?style=flat&logo=javascript&logoColor=black",
    Go: "Go-00ADD8?style=flat&logo=go&logoColor=white",
    Docker: "Docker-2496ED?style=flat&logo=docker&logoColor=white",
    Bun: "Bun-000000?style=flat&logo=bun&logoColor=white",
    Gemini: "Gemini-8E75B2?style=flat&logo=googlegemini&logoColor=white",
    Claude: "Claude-D97757?style=flat&logo=claude&logoColor=white",
};

function link(tool: Tool): string {
    // Internal tools use a relative "?page=..." route inside mai-tools.
    return tool.external ? tool.href : new URL(tool.href, maiToolsUrl).href;
}

function badgeRef(stack: string): string {
    return stack.toLowerCase().replaceAll(" ", "-");
}

function badgeUrl(stack: string): string {
    const known = badges[stack];
    if (known !== undefined) {
        return `https://img.shields.io/badge/${known}`;
    }

    const label = encodeURIComponent(stack.replaceAll("-", "--"));
    return `https://img.shields.io/badge/${label}-555555?style=flat`;
}

function cell(text: string): string {
    return text.replaceAll("|", "\\|");
}

function render(tools: Tool[], readme: Readme): string {
    // Categories keep the order in which they first appear in tools.json.
    const groups = new Map<string, Tool[]>();
    for (const tool of tools) {
        groups.set(tool.category, [...(groups.get(tool.category) ?? []), tool]);
    }

    // One table for every tool so all rows share the same column widths;
    // the category is shown only on the first row of its group.
    const lines: string[] = [
        startMarker,
        "<!-- Generated by scripts/generate-readme.ts from mai-tools' tools.json. Do not edit by hand. -->",
        "",
        `| ${readme.headers.join(" | ")} |`,
        "| --- | --- | --- | --- |",
    ];

    for (const [category, group] of groups) {
        const title = `**${readme.categories[category] ?? category}**`;
        group.forEach((tool, i) => {
            const name = cell(localize(tool.name, readme.locale));
            const text = cell(localize(tool.description, readme.locale));
            const stack = tool.stack.map((s) => `![${s}][${badgeRef(s)}]`).join(" ");
            lines.push(`| ${i === 0 ? title : ""} | [${name}](${link(tool)}) | ${text} | ${stack} |`);
        });
    }

    const usedStacks = [...new Set(tools.flatMap((tool) => tool.stack))];
    lines.push("");
    for (const stack of usedStacks) {
        lines.push(`[${badgeRef(stack)}]: ${badgeUrl(stack)}`);
    }

    lines.push(endMarker);
    return lines.join("\n");
}

const source = Bun.argv[2] ?? defaultSource;
const tools = await loadTools(source);

for (const readme of readmes) {
    const name = readme.path.pathname.split("/").pop();
    const content = await Bun.file(readme.path).text();

    const start = content.indexOf(startMarker);
    const end = content.indexOf(endMarker);
    if (start === -1 || end === -1 || end < start) {
        throw new Error(`${name} must contain ${startMarker} followed by ${endMarker}`);
    }

    const updated = content.slice(0, start) + render(tools, readme) + content.slice(end + endMarker.length);
    await Bun.write(readme.path, updated);
    console.log(`${name}: ${tools.length} tools from ${source}`);
}
